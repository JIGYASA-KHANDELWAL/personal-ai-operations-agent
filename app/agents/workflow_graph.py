"""LangGraph orchestration for the Personal AI Operations Agent.

The graph coordinates existing deterministic/domain functions; it does not send
email or write to Google Calendar. Those actions remain outside the graph and
require explicit user approval/integration before they could be enabled.
"""
from typing import Any, TypedDict
from langgraph.graph import END, START, StateGraph


class PlanningState(TypedDict, total=False):
    goal: str
    plan: dict[str, Any]
    validation_errors: list[str]
    review_status: str
    messages: list[str]


def build_planning_graph():
    def plan_node(state: PlanningState) -> dict:
        from agents.planner import create_plan
        plan = create_plan(state["goal"])
        return {"plan": plan, "messages": ["Plan generated by Gemini planner."]}

    def review_node(state: PlanningState) -> dict:
        plan = state.get("plan", {})
        errors = list(plan.get("validation_errors", []))
        status = "needs_review" if errors else "ready_for_user_review"
        return {
            "validation_errors": errors,
            "review_status": status,
            "messages": state.get("messages", []) + [
                "Scheduling validation completed; user review is still required."
            ],
        }

    graph = StateGraph(PlanningState)
    graph.add_node("generate_plan", plan_node)
    graph.add_node("validate_and_prepare_review", review_node)
    graph.add_edge(START, "generate_plan")
    graph.add_edge("generate_plan", "validate_and_prepare_review")
    graph.add_edge("validate_and_prepare_review", END)
    return graph.compile()


_planning_graph = None

def run_planning_workflow(goal: str) -> PlanningState:
    """Run the graph for one goal and return its final state."""
    global _planning_graph
    if _planning_graph is None:
        _planning_graph = build_planning_graph()
    return _planning_graph.invoke({"goal": goal, "messages": []})
