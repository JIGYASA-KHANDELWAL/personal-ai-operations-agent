
from docx import Document
from datetime import datetime


def generate_document(goal, tasks):
    document = Document()

    document.add_heading("Action Plan", level=0)
    document.add_paragraph(f"Goal: {goal}")
    document.add_paragraph(
        f"Generated on: {datetime.now().strftime('%d %B %Y, %I:%M %p')}"
    )

    document.add_heading("Tasks", level=1)

    for number, task in enumerate(tasks, start=1):
        document.add_heading(
            f"{number}. {task['task']}", level=2
        )

        document.add_paragraph(task["description"])

        priority = task["priority"].capitalize()
        document.add_paragraph(f"Priority: {priority}")

    document.add_paragraph(
        "Generated by Personal AI Operations Agent."
    )

    return document